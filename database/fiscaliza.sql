DROP DATABASE IF EXISTS fiscaliza;
CREATE DATABASE fiscaliza
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;
USE fiscaliza;

-- -------------------------------------------------------------
-- Usuários do sistema (3 níveis: cidadao, agente, admin)
-- Login = e-mail. Senha: SHA-256 com salt derivado do login:
--   salt       = SHA2(LOWER(email), 256)
--   senha_hash = SHA2(CONCAT(salt, senha), 256)
-- -------------------------------------------------------------
CREATE TABLE usuarios (
  id               INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome             VARCHAR(60)  NOT NULL,
  sobrenome        VARCHAR(100) NOT NULL,
  cpf              CHAR(11)     NOT NULL,
  email            VARCHAR(150) NOT NULL,
  data_nascimento  DATE         NOT NULL,
  senha_hash       CHAR(64)     NOT NULL,
  nivel            ENUM('cidadao','agente','admin') NOT NULL DEFAULT 'cidadao',
  ativo            TINYINT(1)   NOT NULL DEFAULT 1,
  criado_em        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em    DATETIME     NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_usuarios_email (email),
  UNIQUE KEY uk_usuarios_cpf (cpf)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Categorias de problemas urbanos
-- -------------------------------------------------------------
CREATE TABLE categorias (
  id         INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome       VARCHAR(80)  NOT NULL,
  descricao  VARCHAR(255) NULL,
  icone      VARCHAR(40)  NULL COMMENT 'Nome do ícone Bootstrap Icons',
  ativo      TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uk_categorias_nome (nome)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Bairros de Araraquara
-- -------------------------------------------------------------
CREATE TABLE bairros (
  id      INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome    VARCHAR(120) NOT NULL,
  regiao  VARCHAR(60)  NULL,
  ativo   TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE KEY uk_bairros_nome (nome)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Denúncias
-- Fluxo: pendente -> (agente aprova) aberta -> em_andamento -> resolvida
--        pendente -> (agente reprova) rejeitada
-- Só denúncias com status diferente de 'pendente' e 'rejeitada'
-- aparecem publicamente.
-- -------------------------------------------------------------
CREATE TABLE denuncias (
  id                INT UNSIGNED NOT NULL AUTO_INCREMENT,
  titulo            VARCHAR(120) NOT NULL,
  descricao         TEXT         NOT NULL,
  endereco          VARCHAR(200) NOT NULL,
  ponto_referencia  VARCHAR(200) NULL,
  categoria_id      INT UNSIGNED NOT NULL,
  bairro_id         INT UNSIGNED NOT NULL,
  autor_id          INT UNSIGNED NOT NULL,
  agente_id         INT UNSIGNED NULL COMMENT 'Agente que avaliou/é responsável',
  status            ENUM('pendente','rejeitada','aberta','em_andamento','resolvida')
                    NOT NULL DEFAULT 'pendente',
  prioridade        ENUM('baixa','media','alta','urgente') NOT NULL DEFAULT 'media',
  motivo_rejeicao   VARCHAR(255) NULL,
  criado_em         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  publicado_em      DATETIME     NULL,
  resolvido_em      DATETIME     NULL,
  atualizado_em     DATETIME     NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_denuncias_status (status),
  KEY idx_denuncias_categoria (categoria_id),
  KEY idx_denuncias_bairro (bairro_id),
  KEY idx_denuncias_autor (autor_id),
  KEY idx_denuncias_agente (agente_id),
  CONSTRAINT fk_denuncias_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
  CONSTRAINT fk_denuncias_bairro    FOREIGN KEY (bairro_id)    REFERENCES bairros (id),
  CONSTRAINT fk_denuncias_autor     FOREIGN KEY (autor_id)     REFERENCES usuarios (id),
  CONSTRAINT fk_denuncias_agente    FOREIGN KEY (agente_id)    REFERENCES usuarios (id)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Fotos das denúncias (upload, troca e remoção)
-- Limites aplicados no PHP: JPG/PNG/WEBP, até 2 MB, até 5 por denúncia
-- -------------------------------------------------------------
CREATE TABLE fotos (
  id             INT UNSIGNED NOT NULL AUTO_INCREMENT,
  denuncia_id    INT UNSIGNED NOT NULL,
  arquivo        VARCHAR(100) NOT NULL COMMENT 'Nome único gerado no servidor',
  nome_original  VARCHAR(255) NOT NULL,
  legenda        VARCHAR(150) NULL,
  tipo_mime      VARCHAR(30)  NOT NULL,
  tamanho_bytes  INT UNSIGNED NOT NULL,
  enviado_em     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_fotos_arquivo (arquivo),
  KEY idx_fotos_denuncia (denuncia_id),
  CONSTRAINT fk_fotos_denuncia FOREIGN KEY (denuncia_id) REFERENCES denuncias (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- Histórico de mudanças de status (acompanhamento pelo cidadão)
-- -------------------------------------------------------------
CREATE TABLE historico (
  id               INT UNSIGNED NOT NULL AUTO_INCREMENT,
  denuncia_id      INT UNSIGNED NOT NULL,
  usuario_id       INT UNSIGNED NOT NULL,
  status_anterior  ENUM('pendente','rejeitada','aberta','em_andamento','resolvida') NULL,
  status_novo      ENUM('pendente','rejeitada','aberta','em_andamento','resolvida') NOT NULL,
  comentario       TEXT NULL,
  criado_em        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_historico_denuncia (denuncia_id),
  CONSTRAINT fk_historico_denuncia FOREIGN KEY (denuncia_id) REFERENCES denuncias (id) ON DELETE CASCADE,
  CONSTRAINT fk_historico_usuario  FOREIGN KEY (usuario_id)  REFERENCES usuarios (id)
) ENGINE=InnoDB;

